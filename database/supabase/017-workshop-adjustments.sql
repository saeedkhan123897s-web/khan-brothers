FOR EACH ROW EXECUTE FUNCTION public.kb_guard_closed_day();

CREATE OR REPLACE FUNCTION public.kb_cancel_workshop(p_job_id bigint,p_cancel jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
    reversal public.kb_workshop_cancellations%ROWTYPE;
    part public.kb_job_parts%ROWTYPE;
    returned integer;
    quantities jsonb := coalesce(p_cancel->'returns','{}'::jsonb);
    key uuid := (p_cancel->>'request_key')::uuid;
BEGIN
    SELECT * INTO job FROM public.kb_workshop_jobs WHERE id=p_job_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Workshop job not found.'; END IF;
    SELECT * INTO reversal FROM public.kb_workshop_cancellations WHERE job_id=p_job_id;
    IF FOUND THEN
        IF reversal.request_key=key THEN RETURN to_jsonb(job); END IF;
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='This cancellation was already recorded.';
    END IF;
    IF job.status IN ('completed','delivered') OR job.status<>p_cancel->>'expected' THEN
        RAISE EXCEPTION USING ERRCODE='23505', MESSAGE='Job status changed. Refresh and try again.';
    END IF;
    IF job.paid_amount IS DISTINCT FROM (p_cancel->>'refund')::numeric THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Payment changed. Review the current refund first.';
    END IF;
    IF EXISTS (SELECT 1 FROM jsonb_object_keys(quantities) k WHERE NOT EXISTS (
        SELECT 1 FROM public.kb_job_parts p WHERE p.job_id=p_job_id AND p.id::text=k
    )) THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='A selected part does not belong to this job.';
    END IF;
    PERFORM 1 FROM public.kb_mechanics WHERE id=job.mechanic_id FOR UPDATE;
    PERFORM 1 FROM public.kb_referral_workshops WHERE id=job.referral_id FOR UPDATE;
    PERFORM 1 FROM public.kb_spare_parts s
    WHERE s.id IN (SELECT p.part_id FROM public.kb_job_parts p WHERE p.job_id=p_job_id)
    ORDER BY s.id FOR UPDATE;
    INSERT INTO public.kb_workshop_cancellations(job_id,request_key,date,reason,refund,refund_account)
    VALUES(p_job_id,key,(p_cancel->>'date')::date,p_cancel->>'reason',job.paid_amount,p_cancel->>'refund_account')
    RETURNING * INTO reversal;
    FOR part IN SELECT * FROM public.kb_job_parts WHERE job_id=p_job_id ORDER BY id LOOP
        returned := coalesce((quantities->>part.id::text)::integer,0);
        IF returned<0 OR returned>part.quantity THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Return quantity must be within the quantity used.';
        END IF;
        INSERT INTO public.kb_workshop_part_returns(cancellation_id,line_id,quantity) VALUES(reversal.id,part.id,returned);
        IF returned>0 THEN
            UPDATE public.kb_spare_parts SET quantity=quantity+returned WHERE id=part.part_id;
        END IF;
    END LOOP;
    UPDATE public.kb_workshop_jobs SET status='cancelled',paid_amount=0,cancelled_on=reversal.date WHERE id=p_job_id RETURNING * INTO job;
    RETURN to_jsonb(job);
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_protect_cancelled_job()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
    IF NEW.status='cancelled' AND (
        (OLD.status<>'cancelled' AND NOT EXISTS(SELECT 1 FROM public.kb_workshop_cancellations WHERE job_id=NEW.id)
            AND (OLD.paid_amount>0 OR EXISTS(SELECT 1 FROM public.kb_job_parts WHERE job_id=NEW.id)))
        OR NEW.paid_amount>0 OR NEW.parts_cost IS DISTINCT FROM OLD.parts_cost
        OR NEW.labour_charge IS DISTINCT FROM OLD.labour_charge OR NEW.labour_cost IS DISTINCT FROM OLD.labour_cost
    ) THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Use the workshop cancellation and refund form.';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS kb_protect_cancelled_job ON public.kb_workshop_jobs;
CREATE TRIGGER kb_protect_cancelled_job BEFORE UPDATE ON public.kb_workshop_jobs
FOR EACH ROW EXECUTE FUNCTION public.kb_protect_cancelled_job();

CREATE OR REPLACE VIEW public.kb_job_part_postings WITH (security_invoker=true) AS
SELECT p.id AS posting_id,p.job_id,p.part_id,p.mechanic_id,p.referral_id,p.date,p.part_name,
    p.quantity,p.unit_price,p.unit_cost,p.revenue,p.commission,p.bonus,
    p.quantity*p.unit_cost AS total_cost
FROM public.kb_job_parts p
UNION ALL
SELECT -r.id,p.job_id,p.part_id,p.mechanic_id,p.referral_id,c.date,p.part_name,
    -p.quantity,p.unit_price,p.unit_cost,-p.revenue,-p.commission,-p.bonus,-r.quantity*p.unit_cost
FROM public.kb_workshop_part_returns r
JOIN public.kb_workshop_cancellations c ON c.id=r.cancellation_id
JOIN public.kb_job_parts p ON p.id=r.line_id;

REVOKE ALL ON public.kb_job_part_postings FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.kb_job_part_postings TO service_role;
REVOKE ALL ON FUNCTION public.kb_cancel_workshop(bigint,jsonb),public.kb_protect_cancelled_job() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.kb_cancel_workshop(bigint,jsonb) TO service_role;

CREATE OR REPLACE FUNCTION public.kb_daily_figures(p_from date, p_to date, p_timezone text)
RETURNS TABLE(day date, sale numeric, sale_income numeric, expense numeric, profit numeric, qist_collected numeric, workshop_income numeric)
LANGUAGE sql STABLE SECURITY INVOKER SET search_path = '' AS $$
    WITH activity(entry_day, sale, sale_income, expense, profit, qist_collected, workshop_income) AS (
        SELECT s.date, s.sell_price, CASE WHEN s.payment_method = 'qist' THEN coalesce(q.advance,0) ELSE s.sell_price END,
            0, s.profit, 0, 0
        FROM public.sales s LEFT JOIN public.qist q ON q.sale_id = s.id WHERE s.date BETWEEN p_from AND p_to
        UNION ALL
        SELECT s.date, s.unit_price * s.quantity, s.unit_price * s.quantity, 0, s.profit, 0, 0
        FROM public.kb_spare_part_sales s WHERE s.date BETWEEN p_from AND p_to
        UNION ALL
        SELECT p.date,p.revenue,0,0,p.revenue-p.total_cost-p.commission-p.bonus,0,0
        FROM public.kb_job_part_postings p WHERE p.date BETWEEN p_from AND p_to
        UNION ALL
        SELECT p.date,0,0,p.amount,0,0,0 FROM public.kb_commission_payments p WHERE p.date BETWEEN p_from AND p_to
        UNION ALL
        SELECT c.date,0,0,0,0,0,-c.refund FROM public.kb_workshop_cancellations c WHERE c.date BETWEEN p_from AND p_to
        UNION ALL
        SELECT e.date, 0, 0, e.amount, -e.amount, 0, 0 FROM public.expenses e WHERE e.date BETWEEN p_from AND p_to
        UNION ALL
        SELECT p.date, 0, 0, 0, 0, p.amount, 0 FROM public.qist_payments p WHERE p.date BETWEEN p_from AND p_to
        UNION ALL
        SELECT p.date, 0, 0, 0, 0, 0, p.amount FROM public.kb_workshop_payments p WHERE p.date BETWEEN p_from AND p_to
        UNION ALL
        SELECT coalesce((j.ready_at AT TIME ZONE p_timezone)::date,j.created_on), 0, 0, 0, j.labour_charge - j.labour_cost, 0, 0
        FROM public.kb_workshop_jobs j
        WHERE j.status IN ('completed','delivered') AND j.labour_charge IS NOT NULL AND j.labour_cost IS NOT NULL
            AND coalesce((j.ready_at AT TIME ZONE p_timezone)::date,j.created_on) BETWEEN p_from AND p_to
    ), days AS (
        SELECT p_from + n AS day FROM generate_series(0,p_to - p_from) n
    )
    SELECT d.day, coalesce(sum(a.sale),0), coalesce(sum(a.sale_income),0), coalesce(sum(a.expense),0),
        coalesce(sum(a.profit),0), coalesce(sum(a.qist_collected),0), coalesce(sum(a.workshop_income),0)
    FROM days d LEFT JOIN activity a ON a.entry_day = d.day GROUP BY d.day ORDER BY d.day
$$;

CREATE OR REPLACE FUNCTION public.kb_snapshot()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path = '' AS $$
    WITH sources(position, source, amount) AS (
        VALUES
            (1, 'bike', (SELECT coalesce(sum(s.profit), 0) FROM public.sales s)),
            (2, 'parts', (SELECT coalesce(sum(p.profit), 0) FROM public.kb_spare_part_sales p) +
                (SELECT coalesce(sum(p.revenue-p.total_cost-p.commission-p.bonus),0) FROM public.kb_job_part_postings p)),
            (3, 'labour', (SELECT coalesce(sum(j.labour_charge - j.labour_cost), 0) FROM public.kb_workshop_jobs j
                WHERE j.status IN ('completed','delivered')))
    )
    SELECT jsonb_build_object(
        'bikes', coalesce((SELECT jsonb_agg(b order by b.id) FROM public.bikes b),'[]'::jsonb),
        'sales', coalesce((SELECT jsonb_agg(s order by s.id) FROM public.sales s),'[]'::jsonb),
        'customers', coalesce((SELECT jsonb_agg(c order by c.id) FROM public.customers c),'[]'::jsonb),
        'qist', coalesce((SELECT jsonb_agg(q order by q.id) FROM public.qist q),'[]'::jsonb),
        'expenses', coalesce((SELECT jsonb_agg(e order by e.id) FROM public.expenses e),'[]'::jsonb),
        'settings', (SELECT to_jsonb(s) FROM public.kb_business_settings s WHERE s.id = 1),
        'profit', (SELECT jsonb_object_agg(source, amount) || jsonb_build_object(
            'net', sum(amount),
            'leading', coalesce((SELECT jsonb_agg(s.source ORDER BY s.position) FROM sources s
                WHERE s.amount > 0 AND s.amount = (SELECT max(amount) FROM sources)), '[]'::jsonb)
        ) FROM sources)
    )
$$;

CREATE OR REPLACE FUNCTION public.kb_profit_entries()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path = '' AS $$
    WITH entries AS (
        SELECT 'bike' AS source, s.id, b.bike_name AS item, s.salesman AS person, s.date,
            1 AS quantity, s.sell_price AS revenue, s.cost_at_sale AS cost, s.profit,
            s.customer_name AS customer, b.purchase_price, b.repair_cost, b.other_cost, b.chassis_no,
            NULL::text AS sku, NULL::numeric AS unit_cost, NULL::numeric AS unit_price
        FROM public.sales s JOIN public.bikes b ON b.id = s.bike_id
        UNION ALL
        SELECT 'parts', s.id, p.name, s.salesman, s.date, s.quantity, s.unit_price * s.quantity,
            s.unit_cost * s.quantity, s.profit, NULL, NULL, NULL, NULL, NULL, p.sku, s.unit_cost, s.unit_price
        FROM public.kb_spare_part_sales s JOIN public.kb_spare_parts p ON p.id = s.part_id
        UNION ALL
        SELECT 'parts',CASE WHEN p.posting_id>0 THEN -2*p.posting_id ELSE 2*p.posting_id+1 END,p.part_name,m.name,p.date,p.quantity,p.revenue,
            p.total_cost+p.commission+p.bonus,p.revenue-p.total_cost-p.commission-p.bonus,
            j.customer_name,NULL,NULL,NULL,NULL,s.sku,p.unit_cost,p.unit_price
        FROM public.kb_job_part_postings p JOIN public.kb_mechanics m ON m.id=p.mechanic_id
        JOIN public.kb_workshop_jobs j ON j.id=p.job_id JOIN public.kb_spare_parts s ON s.id=p.part_id
        UNION ALL
        SELECT 'labour', j.id, j.bike_name, j.mechanic, j.created_on, 1, j.labour_charge, j.labour_cost,
            j.labour_charge - j.labour_cost, j.customer_name, NULL, NULL, NULL, NULL, NULL, NULL, NULL
        FROM public.kb_workshop_jobs j
        WHERE j.status IN ('completed','delivered') AND j.labour_charge IS NOT NULL AND j.labour_cost IS NOT NULL
    )
    SELECT coalesce(jsonb_agg(entries ORDER BY date DESC, source, id DESC), '[]'::jsonb) FROM entries
$$;

CREATE OR REPLACE FUNCTION public.kb_dashboard_series(p_from date,p_day date,p_timezone text,p_monthly boolean)
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$
    WITH extras(day,part_sales,commission,bonus,bike_cost,bike_price) AS (
        SELECT p.date,p.unit_price*p.quantity,0,0,0,0
        FROM public.kb_spare_part_sales p WHERE p.date BETWEEN p_from AND p_day
        UNION ALL
        SELECT p.date,p.revenue,p.commission,p.bonus,0,0 FROM public.kb_job_part_postings p WHERE p.date BETWEEN p_from AND p_day
        UNION ALL
        SELECT s.date,0,0,0,s.cost_at_sale,s.sell_price FROM public.sales s WHERE s.date BETWEEN p_from AND p_day
    ), extra_days AS (
        SELECT e.day,sum(e.part_sales) AS part_sales,sum(e.commission) AS commission,sum(e.bonus) AS bonus,
            sum(e.bike_cost) AS bike_cost,sum(e.bike_price) AS bike_price FROM extras e GROUP BY e.day
    ), period AS (
        SELECT CASE WHEN p_monthly THEN date_trunc('month',f.day::timestamp)::date ELSE f.day END AS day,
            sum(f.sale) AS sale,sum(f.expense) AS expense,sum(f.profit) AS profit,sum(f.qist_collected) AS qist_collected,
            sum(f.workshop_income) AS workshop_income,coalesce(sum(e.part_sales),0) AS part_sales,
            coalesce(sum(e.commission),0) AS commission,coalesce(sum(e.bonus),0) AS bonus,
            coalesce(sum(e.bike_cost),0) AS bike_cost,coalesce(sum(e.bike_price),0) AS bike_price
        FROM public.kb_daily_figures(p_from,p_day,p_timezone) f LEFT JOIN extra_days e ON e.day=f.day
        GROUP BY 1
    )
    SELECT coalesce(jsonb_agg(p ORDER BY p.day),'[]'::jsonb) FROM period p
$$;

CREATE OR REPLACE FUNCTION public.kb_partner_ledger()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$
    WITH owners AS (
        SELECT 'mechanic' AS kind,m.id,m.name,m.phone,NULL::text AS owner,m.rate,
            (SELECT count(*) FROM public.kb_workshop_jobs j WHERE j.mechanic_id=m.id AND j.status<>'cancelled') AS jobs
        FROM public.kb_mechanics m
        UNION ALL
        SELECT 'workshop',r.id,r.name,r.phone,r.owner,10,
            (SELECT count(*) FROM public.kb_workshop_jobs j WHERE j.referral_id=r.id AND j.status<>'cancelled')
        FROM public.kb_referral_workshops r
    ), ledgers AS (
        SELECT o.*,parts.quantity,parts.sales,parts.earned,payout.paid,parts.earned-payout.paid AS remaining
        FROM owners o
        CROSS JOIN LATERAL (
            SELECT coalesce(sum(p.quantity),0) AS quantity,coalesce(sum(p.revenue),0) AS sales,
                coalesce(sum(CASE WHEN o.kind='mechanic' THEN p.commission ELSE p.bonus END),0) AS earned
            FROM public.kb_job_part_postings p
            WHERE (o.kind='mechanic' AND p.mechanic_id=o.id) OR (o.kind='workshop' AND p.referral_id=o.id)
        ) parts
        CROSS JOIN LATERAL (
            SELECT coalesce(sum(p.amount),0) AS paid FROM public.kb_commission_payments p
            WHERE (o.kind='mechanic' AND p.mechanic_id=o.id) OR (o.kind='workshop' AND p.referral_id=o.id)
        ) payout
    )
    SELECT coalesce(jsonb_agg(l ORDER BY l.name,l.id),'[]'::jsonb) FROM ledgers l
$$;

CREATE OR REPLACE FUNCTION public.kb_pay_partner(p_kind text,p_id bigint,p_payment jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    payment public.kb_commission_payments%ROWTYPE;
    key uuid := (p_payment->>'request_key')::uuid;
    paid_amount numeric(13,2) := (p_payment->>'amount')::numeric;
    due numeric;
BEGIN
    IF p_kind='mechanic' THEN PERFORM 1 FROM public.kb_mechanics WHERE id=p_id FOR UPDATE;
    ELSE PERFORM 1 FROM public.kb_referral_workshops WHERE id=p_id FOR UPDATE; END IF;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Partner not found.'; END IF;
    SELECT * INTO payment FROM public.kb_commission_payments WHERE request_key=key;
    IF FOUND THEN
        IF payment.amount IS DISTINCT FROM paid_amount
            OR (CASE WHEN p_kind='mechanic' THEN payment.mechanic_id ELSE payment.referral_id END) IS DISTINCT FROM p_id THEN
            RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='This payment request was already used.';
        END IF;
        RETURN to_jsonb(payment);
    END IF;
    IF p_kind='mechanic' THEN
        SELECT (SELECT coalesce(sum(commission),0) FROM public.kb_job_part_postings WHERE mechanic_id=p_id) -
            (SELECT coalesce(sum(amount),0) FROM public.kb_commission_payments WHERE mechanic_id=p_id) INTO due;
    ELSE
        SELECT (SELECT coalesce(sum(bonus),0) FROM public.kb_job_part_postings WHERE referral_id=p_id) -
            (SELECT coalesce(sum(amount),0) FROM public.kb_commission_payments WHERE referral_id=p_id) INTO due;
    END IF;
    IF paid_amount IS NULL OR paid_amount <= 0 OR paid_amount > due THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Payment must be within the remaining balance.';
    END IF;
    INSERT INTO public.kb_commission_payments(request_key,mechanic_id,referral_id,date,amount)
    VALUES (key,CASE WHEN p_kind='mechanic' THEN p_id END,CASE WHEN p_kind='workshop' THEN p_id END,
        (p_payment->>'date')::date,paid_amount) RETURNING * INTO payment;
    RETURN to_jsonb(payment);
END;
$$;

