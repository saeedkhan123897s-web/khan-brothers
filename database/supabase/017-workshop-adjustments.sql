CREATE TABLE IF NOT EXISTS public.kb_workshop_cancellations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id bigint NOT NULL UNIQUE REFERENCES public.kb_workshop_jobs(id),
    request_key uuid NOT NULL UNIQUE,
    date date NOT NULL,
    reason text NOT NULL CHECK (length(trim(reason)) BETWEEN 1 AND 250),
    refund numeric(13,2) NOT NULL CHECK (refund>=0),
    refund_account text CHECK (refund_account IN ('cash','bank','wallet')),
    CHECK (refund=0 OR refund_account IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS public.kb_workshop_part_returns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cancellation_id bigint NOT NULL REFERENCES public.kb_workshop_cancellations(id),
    line_id bigint NOT NULL UNIQUE REFERENCES public.kb_job_parts(id),
    quantity integer NOT NULL CHECK (quantity>=0)
);

ALTER TABLE public.kb_workshop_cancellations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_workshop_part_returns ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.kb_workshop_cancellations,public.kb_workshop_part_returns FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT ON public.kb_workshop_cancellations,public.kb_workshop_part_returns TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.kb_workshop_cancellations_id_seq,public.kb_workshop_part_returns_id_seq TO service_role;

DROP TRIGGER IF EXISTS kb_guard_closed_day ON public.kb_workshop_cancellations;
