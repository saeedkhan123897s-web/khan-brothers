BEGIN;

ALTER TABLE public.kb_workshop_jobs
    ADD COLUMN IF NOT EXISTS parts_cost numeric(12,2) CHECK (parts_cost >= 0),
    ADD COLUMN IF NOT EXISTS total_bill numeric(13,2) GENERATED ALWAYS AS (
        CASE WHEN parts_cost IS NULL AND labour_charge IS NULL THEN NULL
            ELSE coalesce(parts_cost, 0) + coalesce(labour_charge, 0) END
    ) STORED,
    ADD COLUMN IF NOT EXISTS paid_amount numeric(13,2) NOT NULL DEFAULT 0
        CHECK (paid_amount >= 0 AND paid_amount <= coalesce(total_bill, 0));

CREATE TABLE IF NOT EXISTS public.kb_workshop_payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id bigint NOT NULL REFERENCES public.kb_workshop_jobs(id),
    request_key uuid UNIQUE NOT NULL,
    amount numeric(13,2) NOT NULL CHECK (amount > 0),
    date date NOT NULL
);

ALTER TABLE public.kb_workshop_payments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.kb_workshop_payments FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.kb_workshop_payments TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.kb_workshop_payments_id_seq TO service_role;
CREATE INDEX IF NOT EXISTS kb_workshop_payments_job_idx ON public.kb_workshop_payments(job_id);

CREATE OR REPLACE FUNCTION public.kb_workshop_bill(p_job_id bigint, p_parts_cost numeric, p_labour_charge numeric, p_labour_cost numeric)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
BEGIN
    SELECT * INTO job FROM public.kb_workshop_jobs WHERE id = p_job_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Workshop job not found.';
    END IF;
    IF coalesce(p_parts_cost,0) + coalesce(p_labour_charge,0) < job.paid_amount THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='The bill cannot be lower than the amount already paid.';
    END IF;
    UPDATE public.kb_workshop_jobs
    SET parts_cost = p_parts_cost, labour_charge = p_labour_charge, labour_cost = p_labour_cost
    WHERE id = p_job_id RETURNING * INTO job;
    RETURN to_jsonb(job);
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_record_labour(p_job_id bigint, p_charge numeric, p_cost numeric)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
BEGIN
    SELECT * INTO job FROM public.kb_workshop_jobs WHERE id = p_job_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Workshop job not found.';
    END IF;
    IF job.status NOT IN ('completed','delivered') THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Record labour on a completed or delivered job.';
    END IF;
    RETURN public.kb_workshop_bill(p_job_id, job.parts_cost, p_charge, p_cost);
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_collect_workshop(p_job_id bigint, p_payment jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
    payment public.kb_workshop_payments%ROWTYPE;
    key uuid := (p_payment->>'request_key')::uuid;
    received numeric(13,2) := (p_payment->>'amount')::numeric;
BEGIN
    SELECT * INTO job FROM public.kb_workshop_jobs WHERE id = p_job_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Workshop job not found.';
    END IF;
    SELECT * INTO payment FROM public.kb_workshop_payments WHERE request_key = key;
    IF FOUND THEN
        IF payment.job_id <> p_job_id OR payment.amount IS DISTINCT FROM received THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='This payment request was already used.';
        END IF;
    ELSE
        IF received IS NULL OR received <= 0 OR received > coalesce(job.total_bill,0) - job.paid_amount THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Payment must be within the remaining balance.';
        END IF;
        INSERT INTO public.kb_workshop_payments (job_id, request_key, amount, date)
        VALUES (p_job_id, key, received, (p_payment->>'date')::date) RETURNING * INTO payment;
        UPDATE public.kb_workshop_jobs SET paid_amount = paid_amount + received WHERE id = p_job_id RETURNING * INTO job;
    END IF;
    RETURN jsonb_build_object('id', payment.id, 'job', to_jsonb(job));
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_workshop_status(p_job_id bigint, p_expected text, p_next text)
RETURNS public.kb_workshop_jobs
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
BEGIN
    SELECT * INTO job FROM public.kb_workshop_jobs WHERE id = p_job_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Workshop job not found.'; END IF;
    IF job.status = p_next THEN RETURN job; END IF;
    IF job.status <> p_expected THEN RAISE EXCEPTION USING ERRCODE='23505', MESSAGE='Job status changed. Refresh and try again.'; END IF;
    IF NOT (
        (job.status='received' AND p_next IN ('diagnosing','in_progress','cancelled')) OR
        (job.status='diagnosing' AND p_next IN ('waiting_parts','in_progress','cancelled')) OR
        (job.status='waiting_parts' AND p_next IN ('in_progress','cancelled')) OR
        (job.status='in_progress' AND p_next IN ('waiting_parts','completed','cancelled')) OR
        (job.status='completed' AND p_next='delivered')
    ) THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Invalid workshop status change.'; END IF;
    UPDATE public.kb_workshop_jobs SET status=p_next WHERE id=p_job_id RETURNING * INTO job;
    RETURN job;
END;
$$;

REVOKE ALL ON FUNCTION public.kb_workshop_bill(bigint,numeric,numeric,numeric), public.kb_collect_workshop(bigint,jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.kb_workshop_bill(bigint,numeric,numeric,numeric), public.kb_collect_workshop(bigint,jsonb) TO service_role;

COMMIT;
