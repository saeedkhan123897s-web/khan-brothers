BEGIN;

CREATE TABLE IF NOT EXISTS public.kb_workshop_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid UNIQUE NOT NULL,
    customer_name text NOT NULL CHECK (length(trim(customer_name)) BETWEEN 2 AND 100),
    customer_phone text,
    bike_name text NOT NULL CHECK (length(trim(bike_name)) BETWEEN 2 AND 150),
    registration_number text,
    mileage integer CHECK (mileage >= 0),
    complaints text,
    mechanic text,
    oil_change_on date,
    next_oil_change_on date,
    estimated_cost numeric(12,2) NOT NULL DEFAULT 0 CHECK (estimated_cost >= 0),
    status text NOT NULL DEFAULT 'received' CHECK (status IN ('received','diagnosing','waiting_parts','in_progress','completed','delivered','cancelled')),
    created_on date NOT NULL,
    CHECK (oil_change_on IS NULL OR next_oil_change_on IS NULL OR next_oil_change_on > oil_change_on)
);

ALTER TABLE public.kb_workshop_jobs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.kb_workshop_jobs FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.kb_workshop_jobs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.kb_workshop_jobs_id_seq TO service_role;
CREATE INDEX IF NOT EXISTS kb_workshop_jobs_due ON public.kb_workshop_jobs(next_oil_change_on) WHERE next_oil_change_on IS NOT NULL;

CREATE OR REPLACE FUNCTION public.kb_workshop_status(p_job_id bigint, p_expected text, p_next text)
RETURNS public.kb_workshop_jobs
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
BEGIN
    SELECT * INTO job FROM public.kb_workshop_jobs WHERE id=p_job_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Workshop job not found.'; END IF;
    IF job.status <> p_expected THEN RAISE EXCEPTION USING ERRCODE='23505', MESSAGE='Job status changed. Refresh and try again.'; END IF;
    IF NOT (
        (job.status='received' AND p_next IN ('diagnosing','cancelled')) OR
        (job.status='diagnosing' AND p_next IN ('waiting_parts','in_progress','cancelled')) OR
        (job.status='waiting_parts' AND p_next IN ('in_progress','cancelled')) OR
        (job.status='in_progress' AND p_next IN ('waiting_parts','completed','cancelled')) OR
        (job.status='completed' AND p_next='delivered')
    ) THEN RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Invalid workshop status change.'; END IF;
    UPDATE public.kb_workshop_jobs SET status=p_next WHERE id=p_job_id RETURNING * INTO job;
    RETURN job;
END;
$$;

REVOKE ALL ON FUNCTION public.kb_workshop_status(bigint,text,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.kb_workshop_status(bigint,text,text) TO service_role;

COMMIT;
