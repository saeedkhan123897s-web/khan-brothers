BEGIN;

ALTER TABLE public.bikes
    ADD COLUMN IF NOT EXISTS engine_pct smallint CHECK (engine_pct BETWEEN 0 AND 100),
    ADD COLUMN IF NOT EXISTS body_pct smallint CHECK (body_pct BETWEEN 0 AND 100),
    ADD COLUMN IF NOT EXISTS overall_pct smallint CHECK (overall_pct BETWEEN 0 AND 100);

CREATE TABLE IF NOT EXISTS public.kb_bike_expenses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bike_id bigint NOT NULL REFERENCES public.bikes(id),
    request_key uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    date date NOT NULL,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    amount numeric(12,2) NOT NULL CHECK (amount > 0),
    legacy_kind smallint,
    UNIQUE (bike_id,legacy_kind)
);
CREATE INDEX IF NOT EXISTS kb_bike_expenses_bike_idx ON public.kb_bike_expenses(bike_id);

INSERT INTO public.kb_bike_expenses(bike_id,date,name,amount,legacy_kind)
SELECT b.id,b.purchased_on,c.name,c.amount,c.kind FROM public.bikes b
CROSS JOIN LATERAL (VALUES ('Repair Cost',b.repair_cost,1),('Other Cost',b.other_cost,2)) c(name,amount,kind)
WHERE c.amount > 0 AND NOT EXISTS (SELECT 1 FROM public.kb_bike_expenses e WHERE e.bike_id=b.id AND e.legacy_kind IS NULL)
ON CONFLICT (bike_id,legacy_kind) DO NOTHING;

CREATE OR REPLACE FUNCTION public.kb_initial_bike_expenses()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
    INSERT INTO public.kb_bike_expenses(bike_id,date,name,amount,legacy_kind)
    SELECT NEW.id,NEW.purchased_on,c.name,c.amount,c.kind
    FROM (VALUES ('Repair Cost',NEW.repair_cost,1),('Other Cost',NEW.other_cost,2)) c(name,amount,kind)
    WHERE c.amount > 0;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS kb_initial_bike_expenses ON public.bikes;
CREATE TRIGGER kb_initial_bike_expenses AFTER INSERT ON public.bikes
FOR EACH ROW EXECUTE FUNCTION public.kb_initial_bike_expenses();

CREATE OR REPLACE FUNCTION public.kb_add_bike_expense(p_bike_id bigint,p_expense jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    bike public.bikes%ROWTYPE;
    expense public.kb_bike_expenses%ROWTYPE;
    key uuid := (p_expense->>'request_key')::uuid;
    charge numeric(12,2) := (p_expense->>'amount')::numeric;
BEGIN
    SELECT * INTO bike FROM public.bikes WHERE id=p_bike_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Bike not found.'; END IF;
    SELECT * INTO expense FROM public.kb_bike_expenses WHERE request_key=key AND bike_id=p_bike_id;
    IF NOT FOUND THEN
        IF bike.status <> 'stock' THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Expenses can only be added to bikes in stock.'; END IF;
        IF bike.other_cost + charge > 9999999999.99 THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Bike expenses exceed the allowed total.'; END IF;
        INSERT INTO public.kb_bike_expenses(bike_id,request_key,date,name,amount)
        VALUES (p_bike_id,key,(p_expense->>'date')::date,p_expense->>'name',charge) RETURNING * INTO expense;
        UPDATE public.bikes SET other_cost=other_cost+charge WHERE id=p_bike_id RETURNING * INTO bike;
    END IF;
    RETURN jsonb_build_object('bike',to_jsonb(bike),'expense',to_jsonb(expense));
END;
$$;

CREATE TABLE IF NOT EXISTS public.kb_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid NOT NULL UNIQUE,
    username text NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9_.-]{3,40}$' AND username <> 'admin'),
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    phone text,
    role text NOT NULL CHECK (length(trim(role)) BETWEEN 1 AND 40),
    password_hash text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    permissions text[] NOT NULL DEFAULT '{}',
    version uuid NOT NULL DEFAULT gen_random_uuid(),
    deleted_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.kb_investments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    date date NOT NULL,
    amount numeric(13,2) NOT NULL CHECK (amount > 0),
    note text,
    method text CHECK (method IN ('bank','cash','western_union')),
    opening boolean NOT NULL DEFAULT false,
    CHECK (opening OR method IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS kb_investments_single_opening ON public.kb_investments(opening) WHERE opening;
INSERT INTO public.kb_investments(date,amount,opening)
VALUES ((statement_timestamp() AT TIME ZONE 'Asia/Muscat')::date,120000,true) ON CONFLICT DO NOTHING;

ALTER TABLE public.kb_bike_expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_investments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.kb_bike_expenses, public.kb_users, public.kb_investments FROM PUBLIC, anon, authenticated;
GRANT SELECT,INSERT ON public.kb_bike_expenses, public.kb_investments TO service_role;
GRANT SELECT,INSERT,UPDATE ON public.kb_users TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.kb_bike_expenses_id_seq, public.kb_users_id_seq, public.kb_investments_id_seq TO service_role;
REVOKE ALL ON FUNCTION public.kb_initial_bike_expenses(),public.kb_add_bike_expense(bigint,jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.kb_initial_bike_expenses(),public.kb_add_bike_expense(bigint,jsonb) TO service_role;

COMMIT;
