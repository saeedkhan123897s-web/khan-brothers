BEGIN;

CREATE TABLE IF NOT EXISTS public.kb_spare_part_sales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid UNIQUE NOT NULL,
    part_id bigint NOT NULL REFERENCES public.kb_spare_parts(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_cost numeric(12,2) NOT NULL CHECK (unit_cost >= 0),
    unit_price numeric(12,2) NOT NULL CHECK (unit_price > 0),
    date date NOT NULL,
    profit numeric GENERATED ALWAYS AS ((unit_price - unit_cost) * quantity) STORED
);

ALTER TABLE public.kb_spare_part_sales ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.kb_spare_part_sales FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.kb_spare_part_sales TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.kb_spare_part_sales_id_seq TO service_role;

ALTER TABLE public.kb_workshop_jobs
    ADD COLUMN IF NOT EXISTS labour_charge numeric(12,2) CHECK (labour_charge >= 0),
    ADD COLUMN IF NOT EXISTS labour_cost numeric(12,2) CHECK (labour_cost >= 0);

CREATE OR REPLACE FUNCTION public.kb_sell_spare_part(p_part_id bigint, p_sale jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    part public.kb_spare_parts%ROWTYPE;
    sale public.kb_spare_part_sales%ROWTYPE;
    request_id uuid := (p_sale->>'request_key')::uuid;
    requested_quantity integer := (p_sale->>'quantity')::integer;
    price numeric(12,2) := (p_sale->>'unit_price')::numeric;
BEGIN
    SELECT * INTO part FROM public.kb_spare_parts WHERE id = p_part_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Spare part not found.';
    END IF;
    SELECT * INTO sale FROM public.kb_spare_part_sales WHERE request_key = request_id;
    IF FOUND THEN
        IF sale.part_id <> part.id OR sale.quantity <> requested_quantity OR sale.unit_price <> price THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='This sale request was already used.';
        END IF;
    ELSE
        IF requested_quantity IS NULL OR requested_quantity < 1 OR requested_quantity > part.quantity THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Sale quantity must be within available stock.';
        END IF;
        INSERT INTO public.kb_spare_part_sales (request_key, part_id, quantity, unit_cost, unit_price, date)
        VALUES (request_id, part.id, requested_quantity, part.unit_cost, price, (p_sale->>'date')::date)
        RETURNING * INTO sale;
        UPDATE public.kb_spare_parts SET quantity = quantity - requested_quantity WHERE id = part.id RETURNING * INTO part;
    END IF;
    RETURN jsonb_build_object('sale_id', sale.id, 'part', to_jsonb(part));
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_record_labour(p_job_id bigint, p_charge numeric, p_cost numeric)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
BEGIN
    UPDATE public.kb_workshop_jobs SET labour_charge = p_charge, labour_cost = p_cost
    WHERE id = p_job_id AND status IN ('completed','delivered')
    RETURNING * INTO job;
    IF FOUND THEN RETURN to_jsonb(job); END IF;
    IF NOT EXISTS (SELECT 1 FROM public.kb_workshop_jobs WHERE id = p_job_id) THEN
        RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Workshop job not found.';
    END IF;
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Record labour on a completed or delivered job.';
END;
$$;

REVOKE ALL ON FUNCTION public.kb_sell_spare_part(bigint,jsonb), public.kb_record_labour(bigint,numeric,numeric) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.kb_sell_spare_part(bigint,jsonb), public.kb_record_labour(bigint,numeric,numeric) TO service_role;

CREATE OR REPLACE FUNCTION public.kb_snapshot()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path = '' AS $$
    WITH sources(position, source, amount) AS (
        VALUES
            (1, 'bike', (SELECT coalesce(sum(s.profit), 0) FROM public.sales s)),
            (2, 'parts', (SELECT coalesce(sum(p.profit), 0) FROM public.kb_spare_part_sales p)),
            (3, 'labour', (SELECT coalesce(sum(j.labour_charge - j.labour_cost), 0) FROM public.kb_workshop_jobs j
                WHERE j.status IN ('completed','delivered')))
    )
    SELECT jsonb_build_object(
        'bikes', coalesce((SELECT jsonb_agg(b order by b.id) FROM public.bikes b),'[]'::jsonb),
        'sales', coalesce((SELECT jsonb_agg(s order by s.id) FROM public.sales s),'[]'::jsonb),
        'customers', coalesce((SELECT jsonb_agg(c order by c.id) FROM public.customers c),'[]'::jsonb),
        'qist', coalesce((SELECT jsonb_agg(q order by q.id) FROM public.qist q),'[]'::jsonb),
        'expenses', coalesce((SELECT jsonb_agg(e order by e.id) FROM public.expenses e),'[]'::jsonb),
        'settings', (SELECT to_jsonb(s) FROM public.kb_business_settings s WHERE s.id = 1),
        'profit', (SELECT jsonb_object_agg(source, amount) || jsonb_build_object(
            'net', sum(amount),
            'leading', coalesce((SELECT jsonb_agg(s.source ORDER BY s.position) FROM sources s
                WHERE s.amount > 0 AND s.amount = (SELECT max(amount) FROM sources)), '[]'::jsonb)
        ) FROM sources)
    )
$$;

COMMIT;
