BEGIN;

CREATE TABLE IF NOT EXISTS public.bikes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bike_name text NOT NULL,
    model text NOT NULL,
    photo_url text,
    chassis_no text,
    plate_no text,
    condition_engine text,
    condition_tyre text,
    condition_body text,
    purchase_price numeric(12,2) NOT NULL CHECK (purchase_price >= 0),
    repair_cost numeric(12,2) NOT NULL DEFAULT 0 CHECK (repair_cost >= 0),
    other_cost numeric(12,2) NOT NULL DEFAULT 0 CHECK (other_cost >= 0),
    total_cost numeric(14,2) GENERATED ALWAYS AS (purchase_price + repair_cost + other_cost) STORED,
    sell_price numeric(12,2) CHECK (sell_price > 0),
    status text NOT NULL DEFAULT 'stock' CHECK (status IN ('stock','sold')),
    purchased_on date NOT NULL DEFAULT CURRENT_DATE,
    purchase_method text NOT NULL DEFAULT 'cash' CHECK (purchase_method IN ('cash','bank','jazzcash','easypaisa','card')),
    request_key uuid UNIQUE
);
CREATE UNIQUE INDEX IF NOT EXISTS kb_bikes_chassis ON public.bikes ((upper(regexp_replace(chassis_no, '[^[:alnum:]]', '', 'g'))))
    WHERE chassis_no IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    phone text NOT NULL,
    phone_key text GENERATED ALWAYS AS (regexp_replace(phone, '[^0-9]', '', 'g')) STORED UNIQUE,
    cnic text
);

CREATE TABLE IF NOT EXISTS public.sales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bike_id bigint NOT NULL UNIQUE REFERENCES public.bikes(id),
    customer_id bigint NOT NULL REFERENCES public.customers(id),
    customer_name text NOT NULL,
    customer_phone text NOT NULL,
    customer_cnic text,
    bike_price numeric(14,2) NOT NULL CHECK (bike_price > 0),
    interest_rate numeric(5,2) NOT NULL DEFAULT 0 CHECK (interest_rate >= 0),
    interest_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (interest_amount >= 0),
    sell_price numeric(14,2) NOT NULL CHECK (sell_price = bike_price + interest_amount),
    cost_at_sale numeric(14,2) NOT NULL CHECK (cost_at_sale >= 0),
    payment_method text NOT NULL CHECK (payment_method IN ('cash','bank','jazzcash','easypaisa','card','qist')),
    date date NOT NULL DEFAULT CURRENT_DATE,
    profit numeric(14,2) GENERATED ALWAYS AS (sell_price - cost_at_sale) STORED,
    request_key uuid UNIQUE
);
CREATE INDEX IF NOT EXISTS kb_sales_customer ON public.sales(customer_id);
CREATE INDEX IF NOT EXISTS kb_sales_date ON public.sales(date);

CREATE TABLE IF NOT EXISTS public.qist (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id bigint NOT NULL UNIQUE REFERENCES public.sales(id),
    total numeric(14,2) NOT NULL,
    advance numeric(14,2) NOT NULL CHECK (advance >= 0),
    remaining numeric(14,2) NOT NULL CHECK (remaining >= 0 AND remaining <= total - advance),
    monthly_qist numeric(14,2) NOT NULL CHECK (monthly_qist > 0),
    next_date date,
    status text GENERATED ALWAYS AS (CASE WHEN remaining = 0 THEN 'paid' ELSE 'pending' END) STORED,
    CHECK (remaining = 0 OR next_date IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS kb_qist_due ON public.qist(next_date) WHERE remaining > 0;

CREATE TABLE IF NOT EXISTS public.qist_payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qist_id bigint NOT NULL REFERENCES public.qist(id),
    amount numeric(14,2) NOT NULL CHECK (amount > 0),
    date date NOT NULL DEFAULT CURRENT_DATE,
    request_key uuid UNIQUE
);

CREATE TABLE IF NOT EXISTS public.expenses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type text NOT NULL CHECK (type IN ('Kiraya','Chai','Petrol','Mechanic','Other')),
    amount numeric(12,2) NOT NULL CHECK (amount > 0),
    date date NOT NULL DEFAULT CURRENT_DATE,
    description text,
    request_key uuid UNIQUE
);
CREATE INDEX IF NOT EXISTS kb_expenses_date ON public.expenses(date);

CREATE OR REPLACE FUNCTION public.kb_sell(p_bike_id bigint, p_sale jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    bike public.bikes%ROWTYPE;
    buyer_id bigint;
    sale_id bigint;
    request_id uuid := (p_sale->>'request_key')::uuid;
    base_price numeric(12,2) := (p_sale->>'bike_price')::numeric;
    method text := p_sale->>'payment_method';
    rate numeric(5,2) := CASE WHEN method = 'qist' THEN coalesce((p_sale->>'interest_rate')::numeric,0) ELSE 0 END;
    interest numeric(14,2) := round(base_price * rate / 100,2);
    total numeric(14,2) := base_price + interest;
    advance numeric(14,2) := coalesce((p_sale->>'advance')::numeric,0);
    monthly numeric(14,2) := (p_sale->>'monthly_qist')::numeric;
    today date := (p_sale->>'date')::date;
    due date := (p_sale->>'next_date')::date;
BEGIN
    SELECT * INTO bike FROM public.bikes WHERE id = p_bike_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Bike not found.'; END IF;
    SELECT id INTO sale_id FROM public.sales WHERE request_key=request_id AND bike_id=p_bike_id;
    IF FOUND THEN RETURN sale_id; END IF;
    IF bike.status <> 'stock' THEN RAISE EXCEPTION USING ERRCODE='23505', MESSAGE='This bike is already sold.'; END IF;

    IF method = 'qist' AND (advance >= total OR monthly IS NULL OR monthly > total - advance OR due IS NULL OR due < today) THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Enter a valid advance, monthly Qist and next payment date.';
    END IF;

    INSERT INTO public.customers (name,phone,cnic) VALUES (p_sale->>'customer_name',p_sale->>'customer_phone',p_sale->>'customer_cnic')
    ON CONFLICT (phone_key) DO UPDATE SET cnic=coalesce(public.customers.cnic,excluded.cnic)
    RETURNING id INTO buyer_id;

    INSERT INTO public.sales (bike_id,customer_id,customer_name,customer_phone,customer_cnic,bike_price,interest_rate,
        interest_amount,sell_price,cost_at_sale,payment_method,date,request_key)
    VALUES (bike.id,buyer_id,p_sale->>'customer_name',p_sale->>'customer_phone',p_sale->>'customer_cnic',base_price,rate,
        interest,total,bike.total_cost,method,today,request_id) RETURNING id INTO sale_id;

    IF method = 'qist' THEN
        INSERT INTO public.qist (sale_id,total,advance,remaining,monthly_qist,next_date)
        VALUES (sale_id,total,advance,total-advance,monthly,due);
    END IF;
    UPDATE public.bikes SET status='sold' WHERE id=bike.id;
    RETURN sale_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_collect(p_qist_id bigint, p_payment jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    plan public.qist%ROWTYPE;
    payment_id bigint;
    request_id uuid := (p_payment->>'request_key')::uuid;
    paid numeric(14,2) := (p_payment->>'amount')::numeric;
    today date := (p_payment->>'date')::date;
    due date := (p_payment->>'next_date')::date;
    balance numeric(14,2);
BEGIN
    SELECT * INTO plan FROM public.qist WHERE id=p_qist_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Qist plan not found.'; END IF;
    SELECT id INTO payment_id FROM public.qist_payments WHERE request_key=request_id AND qist_id=p_qist_id;
    IF FOUND THEN RETURN payment_id; END IF;
    IF paid <= 0 OR paid > plan.remaining THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Payment must be within the remaining balance.';
    END IF;
    IF due IS NOT NULL AND due < today THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Next payment date must be today or later.';
    END IF;
    balance := plan.remaining - paid;
    INSERT INTO public.qist_payments (qist_id,amount,date,request_key) VALUES (p_qist_id,paid,today,request_id)
        RETURNING id INTO payment_id;
    UPDATE public.qist SET remaining=balance, next_date=CASE WHEN balance=0 THEN NULL
        ELSE coalesce(due,(plan.next_date + make_interval(months=>floor(paid/plan.monthly_qist)::integer))::date) END
    WHERE id=p_qist_id;
    RETURN payment_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_snapshot()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path = '' AS $$
    SELECT jsonb_build_object(
        'bikes', coalesce((SELECT jsonb_agg(b order by b.id) FROM public.bikes b),'[]'::jsonb),
        'sales', coalesce((SELECT jsonb_agg(s order by s.id) FROM public.sales s),'[]'::jsonb),
        'customers', coalesce((SELECT jsonb_agg(c order by c.id) FROM public.customers c),'[]'::jsonb),
        'qist', coalesce((SELECT jsonb_agg(q order by q.id) FROM public.qist q),'[]'::jsonb),
        'expenses', coalesce((SELECT jsonb_agg(e order by e.id) FROM public.expenses e),'[]'::jsonb)
    )
$$;

