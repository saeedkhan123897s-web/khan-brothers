BEGIN;

CREATE TABLE IF NOT EXISTS public.kb_mechanics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid NOT NULL UNIQUE,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    phone text,
    rate numeric(5,2) NOT NULL DEFAULT 10 CHECK (rate BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS public.kb_referral_workshops (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid NOT NULL UNIQUE,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    owner text NOT NULL CHECK (length(trim(owner)) BETWEEN 1 AND 100),
    phone text
);

ALTER TABLE public.kb_workshop_jobs
    ADD COLUMN IF NOT EXISTS mechanic_id bigint REFERENCES public.kb_mechanics(id),
    ADD COLUMN IF NOT EXISTS referral_id bigint REFERENCES public.kb_referral_workshops(id),
    ADD COLUMN IF NOT EXISTS commission_rate numeric(5,2) CHECK (commission_rate BETWEEN 0 AND 100),
    ADD COLUMN IF NOT EXISTS bonus_rate numeric(5,2) CHECK (bonus_rate BETWEEN 0 AND 100);

CREATE TABLE IF NOT EXISTS public.kb_job_parts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid NOT NULL UNIQUE,
    job_id bigint NOT NULL REFERENCES public.kb_workshop_jobs(id),
    part_id bigint NOT NULL REFERENCES public.kb_spare_parts(id),
    mechanic_id bigint NOT NULL REFERENCES public.kb_mechanics(id),
    referral_id bigint REFERENCES public.kb_referral_workshops(id),
    date date NOT NULL,
    part_name text NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(12,2) NOT NULL CHECK (unit_price > 0),
    unit_cost numeric(12,2) NOT NULL CHECK (unit_cost >= 0),
    commission_rate numeric(5,2) NOT NULL CHECK (commission_rate BETWEEN 0 AND 100),
    bonus_rate numeric(5,2) NOT NULL CHECK (bonus_rate BETWEEN 0 AND 100),
    revenue numeric GENERATED ALWAYS AS (unit_price * quantity) STORED,
    commission numeric GENERATED ALWAYS AS (round(unit_price * quantity * commission_rate / 100,2)) STORED,
    bonus numeric GENERATED ALWAYS AS (round(unit_price * quantity * bonus_rate / 100,2)) STORED
);

CREATE TABLE IF NOT EXISTS public.kb_commission_payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid NOT NULL UNIQUE,
    mechanic_id bigint REFERENCES public.kb_mechanics(id),
    referral_id bigint REFERENCES public.kb_referral_workshops(id),
    date date NOT NULL,
    amount numeric(13,2) NOT NULL CHECK (amount > 0),
    CHECK ((mechanic_id IS NULL) <> (referral_id IS NULL))
);

CREATE INDEX IF NOT EXISTS kb_job_parts_job_idx ON public.kb_job_parts(job_id);
CREATE INDEX IF NOT EXISTS kb_job_parts_date_idx ON public.kb_job_parts(date);
CREATE INDEX IF NOT EXISTS kb_job_parts_mechanic_idx ON public.kb_job_parts(mechanic_id);
CREATE INDEX IF NOT EXISTS kb_job_parts_referral_idx ON public.kb_job_parts(referral_id);
CREATE INDEX IF NOT EXISTS kb_commission_paid_date_idx ON public.kb_commission_payments(date);
CREATE INDEX IF NOT EXISTS kb_workshop_mechanic_idx ON public.kb_workshop_jobs(mechanic_id);
CREATE INDEX IF NOT EXISTS kb_workshop_referral_idx ON public.kb_workshop_jobs(referral_id);

CREATE OR REPLACE FUNCTION public.kb_update_job_partners(p_id bigint,p_mechanic bigint,p_referral bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
    partner public.kb_mechanics%ROWTYPE;
BEGIN
    SELECT * INTO job FROM public.kb_workshop_jobs WHERE id=p_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Workshop job not found.'; END IF;
    IF EXISTS (SELECT 1 FROM public.kb_job_parts WHERE job_id=p_id)
        AND (job.mechanic_id IS DISTINCT FROM p_mechanic OR job.referral_id IS DISTINCT FROM p_referral) THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Partners are already linked to recorded parts.';
    END IF;
    SELECT * INTO partner FROM public.kb_mechanics WHERE id=p_mechanic;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Select a mechanic.'; END IF;
    UPDATE public.kb_workshop_jobs SET mechanic_id=p_mechanic,referral_id=p_referral,mechanic=partner.name,
        commission_rate=CASE WHEN job.mechanic_id=p_mechanic THEN coalesce(job.commission_rate,partner.rate) ELSE partner.rate END,
        bonus_rate=CASE WHEN p_referral IS NULL THEN NULL ELSE coalesce(job.bonus_rate,10) END
    WHERE id=p_id RETURNING * INTO job;
    RETURN to_jsonb(job);
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_add_job_part(p_id bigint,p_part jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
    part public.kb_spare_parts%ROWTYPE;
    line public.kb_job_parts%ROWTYPE;
    key uuid := (p_part->>'request_key')::uuid;
    qty integer := (p_part->>'quantity')::integer;
    price numeric(12,2) := (p_part->>'unit_price')::numeric;
    commission_rate numeric(5,2) := (p_part->>'commission_rate')::numeric;
    bonus_rate numeric(5,2) := (p_part->>'bonus_rate')::numeric;
BEGIN
    SELECT * INTO job FROM public.kb_workshop_jobs WHERE id=p_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Workshop job not found.'; END IF;
    SELECT * INTO line FROM public.kb_job_parts WHERE request_key=key AND job_id=p_id;
    IF FOUND THEN RETURN jsonb_build_object('job',to_jsonb(job),'line',to_jsonb(line)); END IF;
    IF job.status IN ('cancelled','delivered') THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='This job cannot accept more parts.'; END IF;
    IF job.mechanic_id IS NULL THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Select a mechanic.'; END IF;
    PERFORM 1 FROM public.kb_mechanics WHERE id=job.mechanic_id FOR UPDATE;
    IF job.referral_id IS NOT NULL THEN PERFORM 1 FROM public.kb_referral_workshops WHERE id=job.referral_id FOR UPDATE; END IF;
    SELECT * INTO part FROM public.kb_spare_parts WHERE id=(p_part->>'part_id')::bigint FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Spare part not found.'; END IF;
    IF qty IS NULL OR qty <= 0 OR qty > part.quantity THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Sale quantity must be within available stock.'; END IF;
    IF qty * price + coalesce(job.parts_cost,0) > 9999999999.99 THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Parts exceed the allowed job bill.';
    END IF;
    INSERT INTO public.kb_job_parts(request_key,job_id,part_id,mechanic_id,referral_id,date,part_name,quantity,unit_price,unit_cost,commission_rate,bonus_rate)
    VALUES (key,p_id,part.id,job.mechanic_id,job.referral_id,(p_part->>'date')::date,part.name,qty,price,part.unit_cost,
        coalesce(commission_rate,job.commission_rate,10),
        CASE WHEN job.referral_id IS NULL THEN 0 ELSE coalesce(bonus_rate,job.bonus_rate,10) END) RETURNING * INTO line;
    UPDATE public.kb_spare_parts SET quantity=quantity-qty WHERE id=part.id;
    UPDATE public.kb_workshop_jobs SET parts_cost=coalesce(parts_cost,0)+line.revenue,
        commission_rate=line.commission_rate,bonus_rate=CASE WHEN referral_id IS NULL THEN NULL ELSE line.bonus_rate END
    WHERE id=p_id RETURNING * INTO job;
    RETURN jsonb_build_object('job',to_jsonb(job),'line',to_jsonb(line));
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_partner_ledger()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$
    WITH owners AS (
        SELECT 'mechanic' AS kind,m.id,m.name,m.phone,NULL::text AS owner,m.rate,
            (SELECT count(*) FROM public.kb_workshop_jobs j WHERE j.mechanic_id=m.id) AS jobs
        FROM public.kb_mechanics m
        UNION ALL
        SELECT 'workshop',r.id,r.name,r.phone,r.owner,10,
            (SELECT count(*) FROM public.kb_workshop_jobs j WHERE j.referral_id=r.id)
        FROM public.kb_referral_workshops r
    ), ledgers AS (
        SELECT o.*,parts.quantity,parts.sales,parts.earned,payout.paid,parts.earned-payout.paid AS remaining
        FROM owners o
        CROSS JOIN LATERAL (
            SELECT coalesce(sum(p.quantity),0) AS quantity,coalesce(sum(p.revenue),0) AS sales,
                coalesce(sum(CASE WHEN o.kind='mechanic' THEN p.commission ELSE p.bonus END),0) AS earned
            FROM public.kb_job_parts p
            WHERE (o.kind='mechanic' AND p.mechanic_id=o.id) OR (o.kind='workshop' AND p.referral_id=o.id)
        ) parts
        CROSS JOIN LATERAL (
            SELECT coalesce(sum(p.amount),0) AS paid FROM public.kb_commission_payments p
            WHERE (o.kind='mechanic' AND p.mechanic_id=o.id) OR (o.kind='workshop' AND p.referral_id=o.id)
        ) payout
    )
    SELECT coalesce(jsonb_agg(l ORDER BY l.name,l.id),'[]'::jsonb) FROM ledgers l
$$;

CREATE OR REPLACE FUNCTION public.kb_pay_partner(p_kind text,p_id bigint,p_payment jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    payment public.kb_commission_payments%ROWTYPE;
    key uuid := (p_payment->>'request_key')::uuid;
    paid_amount numeric(13,2) := (p_payment->>'amount')::numeric;
    due numeric;
BEGIN
    IF p_kind='mechanic' THEN PERFORM 1 FROM public.kb_mechanics WHERE id=p_id FOR UPDATE;
    ELSE PERFORM 1 FROM public.kb_referral_workshops WHERE id=p_id FOR UPDATE; END IF;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Partner not found.'; END IF;
    SELECT * INTO payment FROM public.kb_commission_payments WHERE request_key=key;
    IF FOUND THEN
        IF payment.amount IS DISTINCT FROM paid_amount
            OR (CASE WHEN p_kind='mechanic' THEN payment.mechanic_id ELSE payment.referral_id END) IS DISTINCT FROM p_id THEN
            RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='This payment request was already used.';
        END IF;
        RETURN to_jsonb(payment);
    END IF;
    IF p_kind='mechanic' THEN
        SELECT (SELECT coalesce(sum(commission),0) FROM public.kb_job_parts WHERE mechanic_id=p_id) -
            (SELECT coalesce(sum(amount),0) FROM public.kb_commission_payments WHERE mechanic_id=p_id) INTO due;
    ELSE
        SELECT (SELECT coalesce(sum(bonus),0) FROM public.kb_job_parts WHERE referral_id=p_id) -
            (SELECT coalesce(sum(amount),0) FROM public.kb_commission_payments WHERE referral_id=p_id) INTO due;
    END IF;
    IF paid_amount IS NULL OR paid_amount <= 0 OR paid_amount > due THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Payment must be within the remaining balance.';
    END IF;
    INSERT INTO public.kb_commission_payments(request_key,mechanic_id,referral_id,date,amount)
    VALUES (key,CASE WHEN p_kind='mechanic' THEN p_id END,CASE WHEN p_kind='workshop' THEN p_id END,
        (p_payment->>'date')::date,paid_amount) RETURNING * INTO payment;
    RETURN to_jsonb(payment);
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_check_job_parts_bill()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
    IF coalesce(NEW.parts_cost,0) < (SELECT coalesce(sum(revenue),0) FROM public.kb_job_parts WHERE job_id=NEW.id) THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Parts cost cannot be lower than the recorded job parts.';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS kb_check_job_parts_bill ON public.kb_workshop_jobs;
CREATE TRIGGER kb_check_job_parts_bill BEFORE UPDATE OF parts_cost ON public.kb_workshop_jobs
FOR EACH ROW EXECUTE FUNCTION public.kb_check_job_parts_bill();

DROP TRIGGER IF EXISTS kb_guard_closed_day ON public.kb_job_parts;
CREATE TRIGGER kb_guard_closed_day BEFORE INSERT ON public.kb_job_parts FOR EACH ROW EXECUTE FUNCTION public.kb_guard_closed_day();
DROP TRIGGER IF EXISTS kb_guard_closed_day ON public.kb_commission_payments;
CREATE TRIGGER kb_guard_closed_day BEFORE INSERT ON public.kb_commission_payments FOR EACH ROW EXECUTE FUNCTION public.kb_guard_closed_day();

ALTER TABLE public.kb_mechanics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_referral_workshops ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_job_parts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_commission_payments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.kb_mechanics, public.kb_referral_workshops, public.kb_job_parts, public.kb_commission_payments FROM PUBLIC, anon, authenticated;
GRANT SELECT,INSERT,UPDATE ON public.kb_mechanics,public.kb_referral_workshops TO service_role;
GRANT SELECT,INSERT ON public.kb_job_parts, public.kb_commission_payments TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.kb_mechanics_id_seq,public.kb_referral_workshops_id_seq,public.kb_job_parts_id_seq,public.kb_commission_payments_id_seq TO service_role;
REVOKE ALL ON FUNCTION public.kb_update_job_partners(bigint,bigint,bigint),public.kb_add_job_part(bigint,jsonb),
    public.kb_partner_ledger(),public.kb_pay_partner(text,bigint,jsonb),public.kb_check_job_parts_bill() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.kb_update_job_partners(bigint,bigint,bigint),public.kb_add_job_part(bigint,jsonb),
    public.kb_partner_ledger(),public.kb_pay_partner(text,bigint,jsonb),public.kb_check_job_parts_bill() TO service_role;

COMMIT;
