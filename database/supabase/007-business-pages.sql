BEGIN;

CREATE TABLE IF NOT EXISTS public.kb_suppliers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid UNIQUE NOT NULL,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    phone text,
    company text,
    address text
);

CREATE TABLE IF NOT EXISTS public.kb_spare_parts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid UNIQUE NOT NULL,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    sku text UNIQUE NOT NULL CHECK (length(trim(sku)) BETWEEN 1 AND 60),
    supplier_id bigint REFERENCES public.kb_suppliers(id),
    quantity integer NOT NULL CHECK (quantity >= 0),
    unit_cost numeric(12,2) NOT NULL CHECK (unit_cost >= 0),
    sell_price numeric(12,2) NOT NULL CHECK (sell_price >= 0)
);

CREATE TABLE IF NOT EXISTS public.kb_staff_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid UNIQUE NOT NULL,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    phone text,
    role text NOT NULL CHECK (role IN ('manager','sales','mechanic','helper')),
    status text NOT NULL CHECK (status IN ('active','inactive'))
);

CREATE TABLE IF NOT EXISTS public.kb_business_settings (
    id bigint PRIMARY KEY CHECK (id = 1),
    business_name text NOT NULL CHECK (length(trim(business_name)) BETWEEN 1 AND 100),
    phone text,
    address text
);
INSERT INTO public.kb_business_settings(id, business_name) VALUES (1, 'Khan Brothers') ON CONFLICT (id) DO NOTHING;

ALTER TABLE public.kb_suppliers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_spare_parts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_staff_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_business_settings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.kb_suppliers, public.kb_spare_parts, public.kb_staff_members, public.kb_business_settings FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.kb_suppliers, public.kb_spare_parts, public.kb_staff_members TO service_role;
GRANT SELECT, UPDATE ON public.kb_business_settings TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.kb_suppliers_id_seq, public.kb_spare_parts_id_seq, public.kb_staff_members_id_seq TO service_role;
CREATE INDEX IF NOT EXISTS kb_spare_parts_supplier_idx ON public.kb_spare_parts(supplier_id);

CREATE OR REPLACE FUNCTION public.kb_snapshot()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path = '' AS $$
    SELECT jsonb_build_object(
        'bikes', coalesce((SELECT jsonb_agg(b order by b.id) FROM public.bikes b),'[]'::jsonb),
        'sales', coalesce((SELECT jsonb_agg(s order by s.id) FROM public.sales s),'[]'::jsonb),
        'customers', coalesce((SELECT jsonb_agg(c order by c.id) FROM public.customers c),'[]'::jsonb),
        'qist', coalesce((SELECT jsonb_agg(q order by q.id) FROM public.qist q),'[]'::jsonb),
        'expenses', coalesce((SELECT jsonb_agg(e order by e.id) FROM public.expenses e),'[]'::jsonb),
        'settings', (SELECT to_jsonb(s) FROM public.kb_business_settings s WHERE s.id = 1)
    )
$$;

COMMIT;
