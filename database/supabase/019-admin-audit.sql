BEGIN;

CREATE TABLE IF NOT EXISTS public.kb_admin_auth (
    id bigint PRIMARY KEY,
    request_key uuid UNIQUE NOT NULL DEFAULT gen_random_uuid(),
    password_hash text,
    mfa_secret text,
    recovery_hashes text[] NOT NULL DEFAULT '{}',
    last_counter bigint NOT NULL DEFAULT -1,
    version uuid NOT NULL DEFAULT gen_random_uuid(),
    revision uuid NOT NULL DEFAULT gen_random_uuid(),
    CHECK (id>=0 AND (id=0 OR password_hash IS NULL))
);

CREATE TABLE IF NOT EXISTS public.kb_audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    actor text NOT NULL,
    action text NOT NULL,
    resource text NOT NULL,
    record_id text NOT NULL,
    fields text[] NOT NULL DEFAULT '{}',
    reason text
);

ALTER TABLE public.kb_admin_auth ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kb_audit_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.kb_admin_auth,public.kb_audit_log FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE ON public.kb_admin_auth TO service_role;
GRANT SELECT,INSERT ON public.kb_audit_log TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.kb_audit_log_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.kb_audit_change()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    before_row jsonb := CASE WHEN TG_OP='INSERT' THEN '{}'::jsonb ELSE to_jsonb(OLD) END;
    after_row jsonb := CASE WHEN TG_OP='DELETE' THEN '{}'::jsonb ELSE to_jsonb(NEW) END;
    target text := coalesce(after_row->>'id',before_row->>'id',after_row->>'date',before_row->>'date');
    changed text[];
    headers jsonb := coalesce(nullif(current_setting('request.headers',true),'')::jsonb,'{}'::jsonb);
BEGIN
    SELECT array_agg(k ORDER BY k) INTO changed
    FROM jsonb_object_keys(before_row||after_row) k
    WHERE before_row->k IS DISTINCT FROM after_row->k
        AND k NOT IN ('request_key','version','revision','last_counter','recovery_hashes','password_hash','mfa_secret',
            'cnic','customer_cnic','phone','customer_phone','photo_url');
    IF TG_TABLE_NAME='kb_users' AND before_row->>'password_hash' IS DISTINCT FROM after_row->>'password_hash' THEN
        changed := array_append(coalesce(changed,'{}'),'credentials');
    END IF;
    IF TG_TABLE_NAME='kb_admin_auth' THEN
        IF TG_OP='UPDATE' AND before_row->>'version'=after_row->>'version' THEN RETURN NEW; END IF;
        changed := ARRAY['credentials'];
    END IF;
    IF changed IS NULL AND TG_OP='UPDATE' THEN RETURN NEW; END IF;
    INSERT INTO public.kb_audit_log(actor,action,resource,record_id,fields,reason)
    VALUES(coalesce(nullif(left(headers->>'x-kb-actor',50),''),'database'),TG_OP,TG_TABLE_NAME,target,
        coalesce(changed,'{}'),CASE WHEN TG_TABLE_NAME='kb_workshop_cancellations' THEN after_row->>'reason'
            WHEN TG_TABLE_NAME='kb_cash_openings' THEN after_row->>'note' END);
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END;
$$;

DO $$
DECLARE table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'kb_users','kb_admin_auth','kb_spare_parts','bikes','sales','expenses','qist_payments','kb_workshop_jobs','kb_workshop_payments',
        'kb_workshop_cancellations','kb_job_parts','kb_commission_payments','kb_investments','kb_day_closings',
        'kb_supplier_bills','kb_supplier_payments','kb_cash_openings'
    ] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS kb_audit_change ON public.%I',table_name);
        EXECUTE format('CREATE TRIGGER kb_audit_change AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.kb_audit_change()',table_name);
    END LOOP;
END;
$$;

REVOKE ALL ON FUNCTION public.kb_audit_change() FROM PUBLIC,anon,authenticated;
COMMIT;
