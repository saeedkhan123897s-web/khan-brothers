CREATE OR REPLACE FUNCTION public.kb_collect(p_qist_id bigint, p_payment jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    plan public.qist%ROWTYPE;
    payment public.qist_payments%ROWTYPE;
    request_id uuid := (p_payment->>'request_key')::uuid;
    paid numeric(14,2) := (p_payment->>'amount')::numeric;
    payment_day date := (p_payment->>'date')::date;
    due date := (p_payment->>'next_date')::date;
    balance numeric(14,2);
    collected numeric;
    months integer;
BEGIN
    SELECT * INTO plan FROM public.qist WHERE id=p_qist_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Qist plan not found.'; END IF;
    SELECT * INTO payment FROM public.qist_payments WHERE request_key=request_id;
    IF FOUND THEN
        IF payment.qist_id<>p_qist_id OR payment.amount<>paid THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='This payment request was already used.';
        END IF;
        RETURN payment.id;
    END IF;
    IF paid IS NULL OR paid <= 0 OR paid > plan.remaining THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Payment must be within the remaining balance.';
    END IF;
    IF due IS NOT NULL AND due < payment_day THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Next payment date must be today or later.';
    END IF;
    balance := plan.remaining - paid;
    collected := greatest(plan.total-plan.advance-plan.remaining,0);
    months := floor((collected+paid)/plan.monthly_qist) - floor(collected/plan.monthly_qist);
    INSERT INTO public.qist_payments(qist_id,amount,date,request_key,account)
    VALUES (p_qist_id,paid,payment_day,request_id,p_payment->>'account') RETURNING * INTO payment;
    UPDATE public.qist SET remaining=balance,next_date=CASE WHEN balance=0 THEN NULL
        ELSE coalesce(due,(plan.next_date+make_interval(months=>months))::date) END WHERE id=p_qist_id;
    RETURN payment.id;
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_collect_workshop(p_job_id bigint, p_payment jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
    job public.kb_workshop_jobs%ROWTYPE;
    payment public.kb_workshop_payments%ROWTYPE;
    key uuid := (p_payment->>'request_key')::uuid;
    received numeric(13,2) := (p_payment->>'amount')::numeric;
BEGIN
    SELECT * INTO job FROM public.kb_workshop_jobs WHERE id = p_job_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Workshop job not found.';
    END IF;
    SELECT * INTO payment FROM public.kb_workshop_payments WHERE request_key = key;
    IF FOUND THEN
        IF payment.job_id <> p_job_id OR payment.amount IS DISTINCT FROM received THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='This payment request was already used.';
        END IF;
    ELSE
        IF received IS NULL OR received <= 0 OR received > coalesce(job.total_bill,0) - job.paid_amount THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Payment must be within the remaining balance.';
        END IF;
        INSERT INTO public.kb_workshop_payments (job_id, request_key, amount, date, account)
        VALUES (p_job_id, key, received, (p_payment->>'date')::date,p_payment->>'account') RETURNING * INTO payment;
        UPDATE public.kb_workshop_jobs SET paid_amount = paid_amount + received WHERE id = p_job_id RETURNING * INTO job;
    END IF;
    RETURN jsonb_build_object('id', payment.id, 'job', to_jsonb(job));
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_pay_partner(p_kind text,p_id bigint,p_payment jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    payment public.kb_commission_payments%ROWTYPE;
    key uuid := (p_payment->>'request_key')::uuid;
    paid_amount numeric(13,2) := (p_payment->>'amount')::numeric;
    due numeric;
BEGIN
    IF p_kind='mechanic' THEN PERFORM 1 FROM public.kb_mechanics WHERE id=p_id FOR UPDATE;
    ELSE PERFORM 1 FROM public.kb_referral_workshops WHERE id=p_id FOR UPDATE; END IF;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002',MESSAGE='Partner not found.'; END IF;
    SELECT * INTO payment FROM public.kb_commission_payments WHERE request_key=key;
    IF FOUND THEN
        IF payment.amount IS DISTINCT FROM paid_amount
            OR (CASE WHEN p_kind='mechanic' THEN payment.mechanic_id ELSE payment.referral_id END) IS DISTINCT FROM p_id THEN
            RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='This payment request was already used.';
        END IF;
        RETURN to_jsonb(payment);
    END IF;
    IF p_kind='mechanic' THEN
        SELECT (SELECT coalesce(sum(commission),0) FROM public.kb_job_part_postings WHERE mechanic_id=p_id) -
            (SELECT coalesce(sum(amount),0) FROM public.kb_commission_payments WHERE mechanic_id=p_id) INTO due;
    ELSE
        SELECT (SELECT coalesce(sum(bonus),0) FROM public.kb_job_part_postings WHERE referral_id=p_id) -
            (SELECT coalesce(sum(amount),0) FROM public.kb_commission_payments WHERE referral_id=p_id) INTO due;
    END IF;
    IF paid_amount IS NULL OR paid_amount <= 0 OR paid_amount > due THEN
        RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Payment must be within the remaining balance.';
    END IF;
    INSERT INTO public.kb_commission_payments(request_key,mechanic_id,referral_id,date,amount,account)
    VALUES (key,CASE WHEN p_kind='mechanic' THEN p_id END,CASE WHEN p_kind='workshop' THEN p_id END,
        (p_payment->>'date')::date,paid_amount,p_payment->>'account') RETURNING * INTO payment;
    RETURN to_jsonb(payment);
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_add_bike_expense(p_bike_id bigint,p_expense jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    bike public.bikes%ROWTYPE;
