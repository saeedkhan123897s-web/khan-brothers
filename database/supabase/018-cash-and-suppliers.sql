CREATE OR REPLACE FUNCTION public.kb_add_supplier_bill(p_bill jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    bill public.kb_supplier_bills%ROWTYPE;
    part public.kb_spare_parts%ROWTYPE;
    part_key bigint := (p_bill->>'part_id')::bigint;
    supplier_key bigint := (p_bill->>'supplier_id')::bigint;
    qty integer := (p_bill->>'quantity')::integer;
    cost numeric := (p_bill->>'amount')::numeric;
    average_cost numeric;
    key uuid := (p_bill->>'request_key')::uuid;
BEGIN
    PERFORM 1 FROM public.kb_suppliers WHERE id=supplier_key FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Supplier not found.'; END IF;
    SELECT * INTO bill FROM public.kb_supplier_bills WHERE request_key=key;
    IF FOUND THEN
        IF bill.supplier_id<>supplier_key THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='This bill request was already used.';
        END IF;
        RETURN to_jsonb(bill);
    END IF;
    IF part_key IS NOT NULL THEN
        SELECT * INTO part FROM public.kb_spare_parts WHERE id=part_key FOR UPDATE;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Spare part not found.'; END IF;
        IF qty IS NULL OR qty<1 OR part.quantity::bigint+qty>2147483647 THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Enter a valid receiving quantity.';
        END IF;
        average_cost := round((part.quantity*part.unit_cost+cost)/(part.quantity::bigint+qty),2);
        IF average_cost>9999999999.99 THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='The received unit cost exceeds the allowed amount.';
        END IF;
        UPDATE public.kb_spare_parts SET quantity=quantity+qty,unit_cost=average_cost WHERE id=part_key;
    END IF;
    INSERT INTO public.kb_supplier_bills(request_key,supplier_id,part_id,quantity,date,description,amount)
    VALUES(key,supplier_key,part_key,qty,(p_bill->>'date')::date,p_bill->>'description',cost)
    RETURNING * INTO bill;
    RETURN to_jsonb(bill);
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_pay_supplier_bill(p_id bigint,p_payment jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE
    bill public.kb_supplier_bills%ROWTYPE;
    payment public.kb_supplier_payments%ROWTYPE;
    key uuid := (p_payment->>'request_key')::uuid;
    charge numeric := (p_payment->>'amount')::numeric;
BEGIN
    PERFORM pg_advisory_xact_lock(80476355270000000+p_id);
    SELECT * INTO bill FROM public.kb_supplier_bills WHERE id=p_id;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Supplier bill not found.'; END IF;
    SELECT * INTO payment FROM public.kb_supplier_payments WHERE request_key=key;
    IF FOUND THEN
        IF payment.bill_id<>p_id OR payment.amount<>charge THEN
            RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='This payment request was already used.';
        END IF;
        RETURN to_jsonb(payment);
    END IF;
    IF charge IS NULL OR charge<=0 OR charge>bill.amount-(SELECT coalesce(sum(amount),0) FROM public.kb_supplier_payments WHERE bill_id=p_id) THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Payment must be within the remaining balance.';
    END IF;
    INSERT INTO public.kb_supplier_payments(request_key,bill_id,date,amount,account)
    VALUES (key,p_id,(p_payment->>'date')::date,charge,p_payment->>'account') RETURNING * INTO payment;
    RETURN to_jsonb(payment);
END;
$$;

CREATE OR REPLACE FUNCTION public.kb_supplier_ledger()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$
    WITH bills AS (
        SELECT b.id,b.date,b.description,b.amount,s.name AS supplier,p.name AS part,b.quantity,
            coalesce(pa.paid,0) AS paid,b.amount-coalesce(pa.paid,0) AS remaining
        FROM public.kb_supplier_bills b JOIN public.kb_suppliers s ON s.id=b.supplier_id
        LEFT JOIN public.kb_spare_parts p ON p.id=b.part_id
        LEFT JOIN LATERAL(SELECT sum(amount) AS paid FROM public.kb_supplier_payments WHERE bill_id=b.id) pa ON true
    )
    SELECT jsonb_build_object('bills',coalesce((SELECT jsonb_agg(b ORDER BY b.date DESC,b.id DESC) FROM bills b),'[]'),
        'balance',coalesce((SELECT sum(remaining) FROM bills),0))
$$;

CREATE OR REPLACE FUNCTION public.kb_money_account(p_method text)
RETURNS text LANGUAGE sql IMMUTABLE SECURITY INVOKER SET search_path='' AS $$
    SELECT CASE WHEN p_method='cash' THEN 'cash' WHEN p_method IN ('bank','card') THEN 'bank'
        WHEN p_method IN ('wallet','jazzcash','easypaisa') THEN 'wallet' ELSE 'unassigned' END
$$;

CREATE OR REPLACE VIEW public.kb_cash_movements WITH (security_invoker=true) AS
SELECT s.date,'Bike sale'::text AS source,s.id AS record_id,public.kb_money_account(s.payment_method) AS account,s.sell_price AS amount
FROM public.sales s WHERE s.payment_method<>'qist'
UNION ALL SELECT s.date,'Qist advance',s.id,coalesce(s.advance_account,'unassigned'),q.advance
    FROM public.sales s JOIN public.qist q ON q.sale_id=s.id WHERE q.advance>0
UNION ALL SELECT date,'Qist payment',id,coalesce(account,'unassigned'),amount FROM public.qist_payments
UNION ALL SELECT date,'Parts sale',id,coalesce(account,'unassigned'),quantity*unit_price FROM public.kb_spare_part_sales
UNION ALL SELECT date,'Workshop payment',id,coalesce(account,'unassigned'),amount FROM public.kb_workshop_payments
UNION ALL SELECT date,'Workshop refund',id,refund_account,-refund FROM public.kb_workshop_cancellations WHERE refund>0
UNION ALL SELECT date,'Commission payout',id,coalesce(account,'unassigned'),-amount FROM public.kb_commission_payments
UNION ALL SELECT date,'Shop expense',id,coalesce(account,'unassigned'),-amount FROM public.expenses
UNION ALL SELECT purchased_on,'Bike purchase',id,public.kb_money_account(purchase_method),-purchase_price FROM public.bikes WHERE purchase_price>0
UNION ALL SELECT e.date,'Bike expense',e.id,coalesce(e.account,
    CASE WHEN e.legacy_kind IS NOT NULL THEN public.kb_money_account(b.purchase_method) END,'unassigned'),-e.amount
    FROM public.kb_bike_expenses e JOIN public.bikes b ON b.id=e.bike_id
UNION ALL SELECT date,'Supplier payment',id,account,-amount FROM public.kb_supplier_payments
UNION ALL SELECT date,'Investment',id,public.kb_money_account(method),amount FROM public.kb_investments WHERE NOT opening;

CREATE OR REPLACE FUNCTION public.kb_cashbook(p_to date,p_from date)
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path='' AS $$
    WITH balances AS (
        SELECT a.account,o.date AS opening_date,o.amount AS opening,coalesce(o.amount,0)+coalesce(m.delta,0) AS amount
        FROM (VALUES ('cash'),('bank'),('wallet'),('unassigned')) a(account)
        LEFT JOIN LATERAL (SELECT date,amount FROM public.kb_cash_openings o
            WHERE o.account=a.account AND o.date<=p_to ORDER BY o.date DESC LIMIT 1) o ON true
        CROSS JOIN LATERAL (SELECT sum(amount) AS delta FROM public.kb_cash_movements m
            WHERE m.account=a.account AND m.date<=p_to AND (o.date IS NULL OR m.date>=o.date)) m
    ), movements AS (
        SELECT * FROM public.kb_cash_movements WHERE date BETWEEN p_from AND p_to
        ORDER BY date DESC,source,record_id DESC LIMIT 500
    )
    SELECT jsonb_build_object('balances',(SELECT jsonb_agg(b) FROM balances b),
        'movements',coalesce((SELECT jsonb_agg(m ORDER BY m.date DESC,m.source,m.record_id DESC) FROM movements m),'[]'),
        'from',p_from,'to',p_to)
$$;

